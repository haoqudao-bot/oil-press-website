## Introduction

Maximizing oil yield is crucial for profitability in oil production. Even small improvements in extraction efficiency can significantly impact your bottom line.

## Understanding Oil Yield

Oil yield is the percentage of oil extracted from raw material:
Yield (%) = (Weight of Oil Extracted / Weight of Raw Material) x 100

## Raw Material Preparation

### Seed Selection
- Use high-quality seeds with high oil content
- Avoid damaged, moldy, or insect-infested seeds
- Select seeds that are fully matured

### Seed Cleaning
- Remove stones, metal, and other hard impurities
- Separate damaged and broken seeds
- Target: Less than 0.5% impurities

### Dehulling
- Increases effective oil content per unit volume
- Reduces wear on pressing equipment
- Recommended removal rates: Peanuts 95%+, Sesame 98%+

### Moisture Conditioning

| Material | Hot Press Moisture | Cold Press Moisture |
|----------|-------------------|---------------------|
| Sesame | 5-6% | 7-8% |
| Peanut | 5-7% | 7-9% |
| Walnut | - | 7-9% |

## Hot Pressing Optimization

### Roasting Process
- Temperature: 160-180°C
- Time: 25-35 minutes
- Output moisture: 3-5%

### Pressing Parameters
- Start with lower pressure, gradually increase
- Maintain maximum pressure for 15-20 minutes
- Standard cycle time: 30-40 minutes per batch

## Cold Pressing Optimization

### Temperature Control
- Maintain pressing temperature below 60°C
- Use specialized cold press equipment
- Recommended models: HN426, HN480, HN500

### Pressure Optimization
- Cold press requires higher pressure to break cell walls
- Use 42+ Mpa/cm2 cake surface pressure
- Extended cycle: ~2 hours per batch

## Post-Pressing Techniques

### Oil Filtration
- Primary filtration: 100-200 mesh
- Fine filtration: 200-300 mesh
- Polishing: 300-500 mesh (optional)

### Oil Settling
- Allow oil to settle for 24-48 hours
- Particles sink to bottom
- Improved oil clarity and quality

## Quality Control

### Yield Monitoring
- Weigh input and output for each batch
- Calculate yield percentage
- Track trends over time

### Equipment Maintenance
- Clean pressing chamber after each batch
- Inspect hydraulic system monthly
- Replace worn parts promptly

## Common Problems and Solutions

### Problem: Low Yield
**Causes:** Poor seed quality, incorrect moisture, insufficient roasting
**Solutions:** Source high-quality seeds, adjust moisture, increase roasting temperature

### Problem: Oil is Cloudy
**Causes:** Incomplete filtration, water contamination
**Solutions:** Increase filtration mesh size, ensure proper drying

### Problem: Pressing Time is Too Long
**Causes:** Seeds too dry, particle size too fine
**Solutions:** Increase moisture content, adjust crushing parameters

## Conclusion

Maximizing oil yield requires attention to every step of the production process. By following these strategies, you can achieve optimal oil yield and maximize the profitability of your oil production business.
