## Introduction

Proper maintenance is essential for ensuring the long-term performance and reliability of your hydraulic oil press.

## Maintenance Schedule

### Daily Maintenance
- Clean the machine and surrounding area
- Check oil levels in hydraulic system
- Inspect pressing chamber for residue
- Verify safety devices are functional

### Weekly Maintenance
- Clean hydraulic oil tank filter
- Check hydraulic connections for leaks
- Inspect electrical connections
- Lubricate moving parts

### Monthly Maintenance
- Check hydraulic oil quality
- Inspect seals and gaskets
- Test pressure gauges
- Calibrate temperature sensors

### Quarterly Maintenance
- Replace hydraulic oil (every 2,000 hours)
- Inspect hydraulic cylinder
- Check frame and structural components
- Test emergency stop function

## Hydraulic System Maintenance

### Hydraulic Oil Management
- Use ISO VG 46 hydraulic oil
- Maintain proper temperature (30-50°C)
- Replace oil every 2,000 operating hours
- Capacity: HN325/HN355: 30-40 liters, HN500: 50-60 liters

### Hydraulic Cylinder Care
- Keep cylinder rod clean
- Protect from dust and debris
- Inspect seals for wear
- Replace if leaking

### Hydraulic Filter Maintenance
- Clean every 50-100 operating hours
- Replace if damaged or excessively dirty
- Use genuine Haonuo replacement filters

## Electrical System Maintenance

### Power Supply Check
- Verify input voltage
- Check for voltage fluctuations
- Use surge protectors

### Motor Maintenance
- Check motor housing for damage
- Inspect fan and cooling system
- Clean cooling fins regularly

### Control Panel Maintenance
- Remove dust from panel
- Check button functionality
- Tighten terminal connections

## Safety Maintenance

### Emergency Systems
- Test emergency stop monthly
- Ensure quick response
- Replace if faulty

### Lockout/Tagout Procedures
1. Turn off power
2. Lock power switch
3. Place "Do Not Operate" tag
4. Verify power is off
5. Perform maintenance

## Troubleshooting Guide

### Problem: Low Pressure
**Causes:** Low hydraulic oil level, contaminated oil, worn pump, leaking seals
**Solutions:** Add oil, filter or replace oil, inspect pump, replace seals

### Problem: Slow Pressing Cycle
**Causes:** Low hydraulic oil temperature, dirty filter, worn pump, low voltage
**Solutions:** Warm up system, clean filter, inspect pump, check power supply

### Problem: Oil Leaks
**Causes:** Worn seals, loose connections, damaged hoses
**Solutions:** Replace seals, tighten connections, replace hoses

### Problem: Machine Won't Start
**Causes:** No power, emergency stop engaged, safety guard open
**Solutions:** Check power supply, reset emergency stop, close safety guards

